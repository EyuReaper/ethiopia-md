#!/usr/bin/env node
/**
 * Copies the SVG for every emoji used by the website into public/emoji/.
 *
 * Scans src/ (not src/content) and knowledge/ for emoji, maps each one to its
 * Twemoji file (rules in src/utils/emoji-core.mjs), copies only the files that
 * are used from node_modules/@twemoji/svg, and writes src/data/emoji-manifest.json.
 * Fails if an emoji has no SVG, so a missing graphic is caught at build time.
 *
 * Twemoji graphics: Copyright Twitter, Inc. and other contributors, CC BY 4.0.
 * Usage: node scripts/utils/build-emoji-assets.mjs   (run automatically by prebuild)
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { join } from 'node:path';
import { emojiFile, findEmoji } from '../../src/utils/emoji-core.mjs';

const SOURCE = 'node_modules/@twemoji/svg';
const OUT = 'public/emoji';
const MANIFEST = 'src/data/emoji-manifest.json';
const ROOTS = ['src', 'knowledge'];
const EXT = /\.(astro|ts|mjs|js|css|json|md)$/;

if (!existsSync(SOURCE)) {
  console.error(
    `Missing ${SOURCE}. Run "npm install" (it is a devDependency) and try again.`,
  );
  process.exit(1);
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    if (p === 'src/content' || name === 'node_modules') return [];
    return statSync(p).isDirectory() ? walk(p) : EXT.test(p) ? [p] : [];
  });
}

// emoji -> files that use it (kept for the manifest and for error messages)
const used = new Map();
for (const root of ROOTS) {
  for (const file of walk(root)) {
    if (file === MANIFEST) continue;
    for (const e of findEmoji(readFileSync(file, 'utf8'))) {
      if (!used.has(e)) used.set(e, new Set());
      used.get(e).add(file);
    }
  }
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const files = new Map(); // svg file name -> one example emoji
const missing = [];
for (const [emoji, where] of used) {
  const name = emojiFile(emoji);
  const src = join(SOURCE, `${name}.svg`);
  if (!existsSync(src)) {
    missing.push(`${emoji} (${name}.svg) in ${[...where][0]}`);
    continue;
  }
  if (!files.has(name)) {
    copyFileSync(src, join(OUT, `${name}.svg`));
    files.set(name, emoji);
  }
}

if (missing.length) {
  console.error('No Twemoji SVG for:\n  ' + missing.join('\n  '));
  process.exit(1);
}

writeFileSync(
  MANIFEST,
  JSON.stringify(
    {
      note: 'Generated by scripts/utils/build-emoji-assets.mjs. Do not edit.',
      source: '@twemoji/svg (Twemoji, CC BY 4.0)',
      count: files.size,
      emoji: Object.fromEntries([...files].sort()),
    },
    null,
    2,
  ) + '\n',
);
console.log(
  `Emoji assets: ${files.size} SVGs copied to ${OUT}/ (from ${used.size} distinct emoji).`,
);
